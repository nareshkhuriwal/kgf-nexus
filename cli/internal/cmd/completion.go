// Shell completion.
//
// The shell scripts are thin: each calls the hidden `nexusctl __complete` with
// the words typed so far, and that walks the REAL command tree. So completion
// can never drift from the commands -- a new verb or flag completes the moment
// it exists, with no script to regenerate -- and the three shells share one
// implementation that is unit tested in Go rather than in shell.

func completionCmd() *command {
	return &command{
		name:    "completion",
		summary: "Print a shell completion script (bash, zsh or fish).",
		usage: `nexusctl completion bash|zsh|fish

Print a completion script. It completes commands, verbs, flags, output formats,
init templates and a few flag values; other operands fall back to file names.

  bash   # current shell:  source <(nexusctl completion bash)
         # permanently:    nexusctl completion bash > /etc/bash_completion.d/nexusctl
         #                 (or ~/.local/share/bash-completion/completions/nexusctl)
  zsh    # current shell:  source <(nexusctl completion zsh)
         # permanently:    nexusctl completion zsh > "${fpath[1]}/_nexusctl"
         #                 (compinit must be enabled)
  fish   # nexusctl completion fish > ~/.config/fish/completions/nexusctl.fish

The script runs nexusctl on every TAB, so nexusctl must be on PATH.`,
		run: func(ctx context.Context, env *Environment, args []string) error {
			rest, err := env.parseFlags(args, nil)
			if err != nil {
				return err
			}
			if len(rest) != 1 {
				return usagef("expected exactly one shell\nUsage: nexusctl completion bash|zsh|fish")
			}
			script, ok := completionScripts[rest[0]]
			if !ok {
				return usagef("unsupported shell %q: expected bash, zsh or fish", rest[0])
			}
			_, err = io.WriteString(env.IO.Out, script)
			return err
		},
	}
}

var completionScripts = map[string]string{
	"bash": `# bash completion for nexusctl. Generated by: nexusctl completion bash
_nexusctl() {
    local IFS=$'\n'
    COMPREPLY=( $(nexusctl __complete "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null) )
}
complete -o default -F _nexusctl nexusctl
`,
	"zsh": `#compdef nexusctl
# zsh completion for nexusctl. Generated by: nexusctl completion zsh
_nexusctl() {
    local -a candidates
    candidates=("${(@f)$(nexusctl __complete "${(@)words[2,CURRENT]}" 2>/dev/null)}")
    candidates=(${candidates:#})
    if (( ${#candidates} )); then
        compadd -Q -- "${candidates[@]}"
    else
        _files
    fi
}
if [ "$funcstack[1]" = "_nexusctl" ]; then
    _nexusctl "$@"
else
    compdef _nexusctl nexusctl
fi
`,
	"fish": `# fish completion for nexusctl. Generated by: nexusctl completion fish
function __nexusctl_complete
    set -l tokens (commandline -opc) (commandline -ct)
    nexusctl __complete $tokens[2..-1] 2>/dev/null
end
complete -c nexusctl -e
complete -c nexusctl -a '(__nexusctl_complete)'
`,
}

// completeCmd is the hidden engine behind the scripts. It is registered as a
// top-level command but deliberately absent from the help text.
func completeCmd() *command {
	return &command{
		name:    "__complete",
		summary: "(internal) shell completion engine",
		usage:   "nexusctl __complete <words...>",
		run: func(ctx context.Context, env *Environment, args []string) error {
			// No flag parsing: every argument is a word the user typed.
			for _, c := range complete(args) {
				fmt.Fprintln(env.IO.Out, c)
			}
			return nil
		},
	}
}

var outputFormats = []string{"table", "json", "yaml"}

// flagValues are the known value sets for value-taking flags.
func flagValues(name string) []string {
	switch name {
	case "o", "output":
		return outputFormats
	case "overlap":
		return overlapPolicies
	case "stream":
		return []string{"stdout", "stderr"}
	case "state":
		return []string{"PENDING", "RUNNING", "PAUSED", "SUCCEEDED", "FAILED", "CANCELLED", "TIMED_OUT"}
	}
	return nil
}

// globalFlagSet is the flag set every command accepts.
func globalFlagSet() *flag.FlagSet {
	fs := flag.NewFlagSet("nexusctl", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	var g GlobalFlags
	g.register(fs)
	fs.Bool("version", false, "")
	return fs
}

// commandFlagSet returns the flags a command registers, by running it with -h
// against a throwaway environment.
//
// Every command's first act is env.parseFlags, which registers its flags and
// then parses; -h makes the parse return flag.ErrHelp before the command does
// anything else. The context is already cancelled as a second guard, so even a
// command that broke that convention could not reach the network.
func commandFlagSet(c *command) *flag.FlagSet {
	fs := flag.NewFlagSet(c.name, flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	fs.Usage = func() {}
	env := &Environment{
		IO:      IO{Out: io.Discard, Err: io.Discard, In: strings.NewReader("")},
		Env:     func(string) string { return "" },
		flagSet: fs,
	}
	env.Globals.register(fs)
	if c.name != "__complete" {
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		_ = c.run(ctx, env, []string{"-h"})
	}
	return fs
}

func flagNames(fs *flag.FlagSet) []string {
	var names []string
	fs.VisitAll(func(f *flag.Flag) {
		if len(f.Name) == 1 {
			names = append(names, "-"+f.Name)
		} else {
			names = append(names, "--"+f.Name)
		}
	})
	sort.Strings(names)
	return names
}

// takesValue reports whether a word is a flag that consumes the next word.
func takesValue(fs *flag.FlagSet, word string) (string, bool) {
	if len(word) < 2 || word[0] != '-' || strings.Contains(word, "=") || word == "--" {
		return "", false
	}
	name := strings.TrimLeft(word, "-")
	f := fs.Lookup(name)
	if f == nil || isBoolFlag(f) {
		return name, false
	}
	return name, true
}

// positionals strips flags (and the values they consume) from words.
func positionals(fs *flag.FlagSet, words []string) []string {
	var out []string
	for i := 0; i < len(words); i++ {
		w := words[i]
		if len(w) > 1 && w[0] == '-' {
			if _, v := takesValue(fs, w); v {
				i++
			}
			continue
		}
		out = append(out, w)
	}
	return out
}

func filterPrefix(cands []string, prefix string) []string {
	var out []string
	for _, c := range cands {
		if strings.HasPrefix(c, prefix) {
			out = append(out, c)
		}
	}
	return out
}

// complete returns the candidates for the last word, given everything typed
// before it. An empty result tells the shell to fall back to file names.
func complete(words []string) []string {
	if len(words) == 0 {
		words = []string{""}
	}
	prior, cur := words[:len(words)-1], words[len(words)-1]

	// Which command are we in? Walk the positional words with the global flags.
	global := globalFlagSet()
	pos := positionals(global, prior)

	var target *command
	var targetGroup *group
	var afterCommand []string // words typed after the command name
	if len(pos) > 0 {
		for _, c := range topLevel() {
			if c.name == pos[0] {
				target = c
			}
		}
		for _, g := range groups() {
			if g.name == pos[0] {
				targetGroup = g
			}
		}
		if targetGroup != nil && len(pos) > 1 {
			for _, c := range targetGroup.commands {
				if c.name == pos[1] {
					target = c
				}
			}
		}
	}

	fs := global
	if target != nil {
		fs = commandFlagSet(target)
		// Words after the command's own name, for positional counting.
		skip := 1
		if targetGroup != nil {
			skip = 2
		}
		afterCommand = positionals(fs, prior)
		if len(afterCommand) >= skip {
			afterCommand = afterCommand[skip:]
		}
	}

	// Completing a flag's value?
	if len(prior) > 0 {
		if name, v := takesValue(fs, prior[len(prior)-1]); v {
			return filterPrefix(flagValues(name), cur)
		}
	}
	if strings.HasPrefix(cur, "-") {
		return filterPrefix(flagNames(fs), cur)
	}

	switch {
	case len(pos) == 0:
		var names []string
		for _, g := range groups() {
			names = append(names, g.name)
		}
		for _, c := range topLevel() {
			if !strings.HasPrefix(c.name, "_") {
				names = append(names, c.name)
			}
		}
		names = append(names, "help")
		sort.Strings(names)
		return filterPrefix(names, cur)
	case pos[0] == "help":
		if len(pos) == 1 {
			return complete([]string{cur})
		}
		for _, g := range groups() {
			if g.name == pos[1] && len(pos) == 2 {
				return filterPrefix(verbNames(g), cur)
			}
		}
		return nil
	case targetGroup != nil && target == nil:
		if len(pos) == 1 {
			return filterPrefix(verbNames(targetGroup), cur)
		}
		return nil
	case target != nil:
		switch target.name {
		case "init":
			if len(afterCommand) == 0 {
				return filterPrefix(templates.Names(), cur)
			}
		case "completion":
			if len(afterCommand) == 0 {
				return filterPrefix([]string{"bash", "fish", "zsh"}, cur)
			}
		case "config":
			if len(afterCommand) == 0 {
				return filterPrefix([]string{"view"}, cur)
			}
		}
	}
	return nil
}

func verbNames(g *group) []string {
	names := make([]string, 0, len(g.commands))
	for _, c := range g.commands {
		names = append(names, c.name)
	}
	sort.Strings(names)
	return names
}
